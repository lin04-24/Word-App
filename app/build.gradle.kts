val releaseStoreFile = providers.environmentVariable("WORD_APP_RELEASE_STORE_FILE").orNull
val releaseStorePassword = providers.environmentVariable("WORD_APP_RELEASE_STORE_PASSWORD").orNull
val releaseKeyAlias = providers.environmentVariable("WORD_APP_RELEASE_KEY_ALIAS").orNull
val releaseKeyPassword = providers.environmentVariable("WORD_APP_RELEASE_KEY_PASSWORD").orNull
val hasReleaseSigning = listOf(
    releaseStoreFile,
    releaseStorePassword,
    releaseKeyAlias,
    releaseKeyPassword,
).all { !it.isNullOrBlank() }

if (gradle.startParameter.taskNames.any { it.contains("release", ignoreCase = true) } && !hasReleaseSigning) {
    error("Release signing is not configured. Set WORD_APP_RELEASE_STORE_FILE, WORD_APP_RELEASE_STORE_PASSWORD, WORD_APP_RELEASE_KEY_ALIAS, and WORD_APP_RELEASE_KEY_PASSWORD.")
}

